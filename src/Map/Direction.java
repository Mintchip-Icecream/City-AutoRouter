package Map;

/**
 * Enum representing the body relative directions, left, right, forward, and backwards.
 *
 * @author June Flores
 * @version 11/15/25
 */
public enum Direction {
    /**
     * The direction of "left", in the context of turning left.
     */
    LEFT,
    /**
     * The direction of "right" in the context of turning right.
     */
    RIGHT,
    /**
     * The direction of "right" in the context of the opposite direction to one is moving in
     */
    BACK,
    /**
     * The direction of "forward" in the context of moving in a direction.
     */
    FORWARD;
}
